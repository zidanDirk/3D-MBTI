export const questionBank = worlds.flatMap(({ dimension }) => [
  ...baseQuestions.filter((question) => question.dimension === dimension),
  ...extraScenarios[dimension].map(([title, description, leftText, leftDetail, rightText, rightDetail]) => ({
    dimension, title, description, options: [
      { text: leftText, detail: leftDetail, value: dimension[0] },
      { text: rightText, detail: rightDetail, value: dimension[1] },
    ],
  })),
].map((question, index) => ({ ...question, id: `${dimension.toLowerCase()}-${String(index + 1).padStart(2, '0')}` })));

export function getQuestions(tierId = 'quick') {
  const tier = tiers.find(({ id }) => id === tierId);
  if (!tier) throw new TypeError('未知题目档位。');
  return worlds.flatMap(({ dimension }) => questionBank.filter((question) => question.dimension === dimension).slice(0, tier.count / 4))
    .map((question) => ({ ...question, options: question.options.map((option) => ({ ...option })) }));
}

