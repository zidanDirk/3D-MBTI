export function getProfile(type) {
  if (!Object.hasOwn(profiles, type)) throw new TypeError('未知人格类型。');
  const [name, tagline, description, tags] = profiles[type];
  const color = type.includes('N') ? (type.includes('T') ? '#be6bff' : '#46ffbb') : (type.endsWith('J') ? '#4fe5ff' : '#ffe46b');
  return { type, name, tagline, description, tags: [...tags], color };
}

export function calculateResult(answers, items = questions) {
  if (!Array.isArray(items) || ![12, 32, 60].includes(items.length) ||
      worlds.some(({ dimension }) => items.filter((q) => q?.dimension === dimension).length !== items.length / 4) ||
      items.some((q) => !Array.isArray(q.options) || q.options.length !== 2 || !q.dimension.split('').every((value) => q.options.some((option) => option.value === value)))) {
    throw new TypeError('题目集必须完整且四个维度均衡。');
  }
  if (!Array.isArray(answers) || answers.length !== items.length) {
    throw new TypeError(`请完成全部 ${items.length} 个情境选择。`);
  }
  Array.from(answers).forEach((answer, index) => {
    if (!items[index].options.some((option) => option.value === answer)) {
      throw new TypeError(`第 ${index + 1} 个选择无效。`);
    }
  });
  const percentages = worlds.map(({ dimension }) => {
    const [left, right] = dimension;
    const choices = answers.filter((answer, index) => items[index].dimension === dimension);
    const leftCount = choices.filter((answer) => answer === left).length;
    return { dimension, left, right, leftPercent: Math.round(100 * leftCount / choices.length), balanced: leftCount * 2 === choices.length };
  });
  const type = percentages.map(({ left, right, leftPercent }) => leftPercent > 50 ? left : right).join('');
  const tieDimensions = percentages.filter((p) => p.balanced).map((p) => p.dimension);
  return { ...getProfile(type), percentages, provisional: tieDimensions.length > 0, tieDimensions, questionCount: items.length };
}
